export function localizedTemplate(
  template: ChartTemplate,
  language: "zh" | "en",
): { name: string; description: string } {
  if (language !== "en") return { name: template.name, description: template.description };
  return CHART_TEMPLATE_EN[template.id] ?? {
    name: template.name,
    description: template.description,
  };
}

