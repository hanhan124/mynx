// Generate the installer include_bytes! list from src-tauri/r.
// The generated source is build input and is intentionally not hand-maintained.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const sourceRoot = path.join(root, "src-tauri", "r");
const output = path.join(root, "installer", "src-tauri", "src", "generated_resources.rs");

const files = [];
function walk(dir, rel = "") {
  for (const name of fs.readdirSync(dir).sort()) {
    const absolute = path.join(dir, name);
    const relative = rel ? `${rel}/${name}` : name;
    if (fs.statSync(absolute).isDirectory()) walk(absolute, relative);
    else files.push(relative.replace(/\\/g, "/"));
  }
}
walk(sourceRoot);

const body = files.map((relative) => {
  // Rust accepts forward slashes in include_bytes paths on Windows; keeping
  // them avoids backslash escape sequences such as \t and \r in string literals.
  return `    ("r/${relative}", include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/resources/r/${relative}"))),`;
}).join("\n");
const source = `// @generated by scripts/generate-installer-resources.cjs; do not edit.\n\npub const R_RESOURCES: &[(&str, &[u8])] = &[\n${body}\n];\n`;
fs.writeFileSync(output, source, "utf8");
console.log(`Generated installer resource list: ${files.length} files`);
