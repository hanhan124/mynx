// Generate installer include_bytes! declarations from the compressed main
// payload manifest and src-tauri/r. Do not hand-maintain the output.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const root = path.join(__dirname, "..");
const sourceRoot = path.join(root, "src-tauri", "r");
const output = path.join(root, "installer", "src-tauri", "src", "generated_resources.rs");
const payloadManifestPath = path.join(root, "installer", "src-tauri", "resources", "mynx-payload.json");
const payload = JSON.parse(fs.readFileSync(payloadManifestPath, "utf8"));
const compressedPayload = path.join(path.dirname(payloadManifestPath), payload.embedded_payload?.filename ?? "");
const resourceRoot = path.dirname(payloadManifestPath);
const uninstallerName = payload.uninstaller?.filename ?? "";
const uninstallerPath = path.join(resourceRoot, uninstallerName);

if (!payload.size_bytes || payload.embedded_payload?.compression !== "gzip" || !fs.existsSync(compressedPayload)) {
  throw new Error("缺少经过校验的 gzip 主程序 payload 清单");
}
if (!uninstallerName || path.basename(uninstallerName) !== uninstallerName || !fs.existsSync(uninstallerPath)) {
  throw new Error("缺少独立卸载程序；请先运行 npm run installer:uninstaller");
}
const uninstallerBytes = fs.readFileSync(uninstallerPath);
const uninstallerSha = crypto.createHash("sha256").update(uninstallerBytes).digest("hex");
if (
  uninstallerBytes.length === 0 ||
  uninstallerBytes.length !== payload.uninstaller.size_bytes ||
  uninstallerSha !== payload.uninstaller.sha256
) {
  throw new Error("独立卸载程序与 payload 清单中的大小或 SHA-256 不一致");
}

const files = [];
function walk(dir, rel = "") {
  for (const name of fs.readdirSync(dir).sort()) {
    const absolute = path.join(dir, name);
    const relative = rel ? `${rel}/${name}` : name;
    if (fs.statSync(absolute).isDirectory()) walk(absolute, relative);
    else files.push(relative.replace(/\\/g, "/"));
  }
}
walk(sourceRoot);

const body = files.map((relative) => {
  // Rust accepts forward slashes in include_bytes paths on Windows; keeping
  // them avoids backslash escape sequences such as \t and \r in string literals.
  return `    ("r/${relative}", include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/resources/r/${relative}"))),`;
}).join("\n");
const source = `// @generated by scripts/generate-installer-resources.cjs; do not edit.\n\n\
pub const MYNX_PAYLOAD_GZIP: &[u8] = include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/resources/${payload.embedded_payload.filename}"));\n\
pub const MYNX_PAYLOAD_UNCOMPRESSED_SIZE: u64 = ${payload.size_bytes};\n\
pub const MYNX_UNINSTALLER: &[u8] = include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/resources/${uninstallerName}"));\n\
pub const MYNX_UNINSTALLER_SIZE: u64 = ${uninstallerBytes.length};\n\
pub const R_RESOURCES: &[(&str, &[u8])] = &[\n${body}\n];\n`;
fs.writeFileSync(output, source, "utf8");
console.log(`Generated installer resource list: ${files.length} files`);
